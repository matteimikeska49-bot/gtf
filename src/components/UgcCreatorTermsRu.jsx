const UgcSEOHead = () => {
  useEffect(() => {
    const title = 'Условия участия для UGC-креаторов GoToFlow';
    const desc = 'Условия участия UGC-креаторов в программе GoToFlow: форматы контента, оплата за подтверждённые просмотры, требования к публикациям, выплаты и права на контент.';
    document.title = title;

    const setMeta = (name, content, prop = false) => {
      const sel = prop ? `meta[property="${name}"]` : `meta[name="${name}"]`;
      let el = document.querySelector(sel);
      if (!el) { el = document.createElement('meta'); document.head.appendChild(el); }
      el.setAttribute(prop ? 'property' : 'name', name);
      el.setAttribute('content', content);
    };

    const setLink = (rel, href) => {
      const sel = `link[rel="${rel}"]:not([hreflang])`;
      let el = document.querySelector(sel);
      if (!el) { el = document.createElement('link'); document.head.appendChild(el); }
      el.setAttribute('rel', rel); el.setAttribute('href', href);
    };

    setMeta('title', title);
    setMeta('description', desc);
    setMeta('og:title', title, true);
    setMeta('og:description', desc, true);
    setMeta('twitter:title', title, true);
    setMeta('twitter:description', desc, true);

    setLink('canonical', 'https://gotoflow.io/ru/ugc-creator-terms');
    document.documentElement.lang = 'ru';

    return () => { document.title = 'GoToFlow'; };
  }, []);

  return null;
};

